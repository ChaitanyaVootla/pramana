/*
 * Conventions
 * - Primary keys are UUIDv7 generated by the application (time-ordered).
 * - Content tables carry `version`, bumped on every applied update; history is
 *   reconstructable from `events` (and `page_revisions` for pages).
 * - Semi-structured fields are JSONB validated by the zod schemas in @pramana/core
 *   before they are written. The database never sees unvalidated JSON.
 * - `search_text` is accent-folded by the application; `search` is a generated
 *   tsvector over it (no Postgres extensions needed).
 */

const tsvector = customType<{ data: string }>({ dataType: () => "tsvector" });
const ts = (name: string) => timestamp(name, { withTimezone: true, mode: "date" });
const now = () => sql`now()`;
const searchVector = () =>
  tsvector("search").generatedAlwaysAs(sql`to_tsvector('simple', coalesce(search_text, ''))`);


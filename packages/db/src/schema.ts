/**
 * A learner's answers: "Guess first" questions, end-of-chapter checks,
 * "Did you believe this?" on misconceptions, chapters read, and the first-steps
 * questions for a new learner. `actor_id` is the learner;
 * who recorded it (the web UI or an agent acting for them) is in `events`.
 * `response` and `result` are validated by GuessResponse / CheckResponse /
 * Belief and LearnResult in @pramana/core.
 */
export const learnerResponses = pgTable(
  "learner_responses",
  {
    id: uuid("id").primaryKey(),
    actorId: uuid("actor_id")
      .notNull()
      .references(() => actors.id),
    /** Null for questions that belong to no page ("first steps"). */
    pageId: uuid("page_id").references(() => pages.id),
    /** The block answered; for "read", the chapter; for "first", "first-steps". */
    blockId: text("block_id").notNull(),
    /** The check item or first step; "" for guesses, beliefs and reads. */
    itemId: text("item_id").notNull().default(""),
    kind: text("kind").$type<"guess" | "skip" | "check" | "belief" | "read" | "skim" | "first">().notNull(),
    /** The claim the answer is about (the guess's or recall item's claim, the misconception). */
    claimId: uuid("claim_id").references(() => claims.id),
    response: jsonb("response").$type<Record<string, unknown>>().notNull(),
    result: jsonb("result").$type<Record<string, unknown> | null>(),
    correct: integer("correct"), // 1 / 0 / null
    /** Confidence before the answer, in percent (SURENESS_PERCENT). */
    confidence: integer("confidence"),
    at: ts("at").notNull().default(now()),
  },
  (t) => [
    index("learner_responses_page_idx").on(t.actorId, t.pageId),
    index("learner_responses_at_idx").on(t.actorId, t.at),
  ],
);

// ---------------------------------------------------------------------------
// Personal workspace: canvases and per-user page views. Owned by one learner,
// not content: no changesets, but every write is audited (events) and the
// JSONB is validated by CanvasItemContent / CanvasLayout / UserView.
// ---------------------------------------------------------------------------

/** A learner's board. `version` is bumped on every change to it or its items (live refresh). */
export const canvases = pgTable(
  "canvases",
  {
    id: uuid("id").primaryKey(),
    ownerId: uuid("owner_id")
      .notNull()
      .references(() => actors.id),
    title: text("title").notNull(),
    description: text("description"),
    version: integer("version").notNull().default(1),
    createdAt: ts("created_at").notNull().default(now()),
    updatedAt: ts("updated_at").notNull().default(now()),
  },
  (t) => [index("canvases_owner_idx").on(t.ownerId, t.updatedAt)],
);

/** One thing on a canvas: a reference to site content (rendered live) or the learner's own text. */
export const canvasItems = pgTable(
  "canvas_items",
  {
    id: uuid("id").primaryKey(),
    canvasId: uuid("canvas_id")
      .notNull()
      .references(() => canvases.id, { onDelete: "cascade" }),
    kind: text("kind").notNull(),
    content: jsonb("content").$type<CanvasItemContent>().notNull(),
    layout: jsonb("layout").$type<CanvasLayout>().notNull(),
    /** Who put it there (the learner, or their AI). */
    addedById: uuid("added_by_id")
      .notNull()
      .references(() => actors.id),
    /** "pending": added by the learner's AI and not yet kept (shown with Keep / Remove); else "kept". */
    status: text("status").$type<"kept" | "pending">().notNull().default("kept"),
    /** Items added in one call share a batch, so an AI's additions can be kept or undone together. */
    batchId: uuid("batch_id"),
    version: integer("version").notNull().default(1),
    createdAt: ts("created_at").notNull().default(now()),
    updatedAt: ts("updated_at").notNull().default(now()),
  },
  (t) => [index("canvas_items_canvas_idx").on(t.canvasId)],
);

/** A line between two items on a canvas, with how they relate (CanvasRelation) and a label. */
export const canvasLinks = pgTable(
  "canvas_links",
  {
    id: uuid("id").primaryKey(),
    canvasId: uuid("canvas_id")
      .notNull()
      .references(() => canvases.id, { onDelete: "cascade" }),
    fromId: uuid("from_id")
      .notNull()
      .references(() => canvasItems.id, { onDelete: "cascade" }),
    toId: uuid("to_id")
      .notNull()
      .references(() => canvasItems.id, { onDelete: "cascade" }),
    relation: text("relation").notNull(),
    label: text("label"),
    addedById: uuid("added_by_id")
      .notNull()
      .references(() => actors.id),
    status: text("status").$type<"kept" | "pending">().notNull().default("kept"),
    batchId: uuid("batch_id"),
    createdAt: ts("created_at").notNull().default(now()),
  },
  (t) => [index("canvas_links_canvas_idx").on(t.canvasId)],
);

/** One learner's view of one page or entity, laid over its spec ("Customise this page"). */
export const userViews = pgTable(
  "user_views",
  {
    id: uuid("id").primaryKey(),
    ownerId: uuid("owner_id")
      .notNull()
      .references(() => actors.id),
    /** "page" (era pages, by page id), "entity" (entity pages, by entity id) or "site" (one per learner, id SITE_VIEW_ID). */
    subjectType: text("subject_type").$type<"page" | "entity" | "site">().notNull(),
    subjectId: uuid("subject_id").notNull(),
    view: jsonb("view").$type<UserView>().notNull(),
    /** Recent changes, newest last, each with the view before it (for "Undo"). */
    history: jsonb("history").$type<UserViewChange[]>().notNull().default([]),
    version: integer("version").notNull().default(1),
    updatedAt: ts("updated_at").notNull().default(now()),
  },
  (t) => [uniqueIndex("user_views_subject").on(t.ownerId, t.subjectType, t.subjectId)],
);
